#
#   · `views/macro_view.py`       (Streamlit 화면)  ← 최신
#   · `web/pages/macro_page.py`   (NiceGUI 화면)    ← 위와 글자 단위로 동일
#   · `utils/macro_ai.py`         (Gemini 프롬프트) ← **옛 이름이 그대로 남아 있었음**
#
# 세 번째가 문제였습니다. `utils/macro_ai.py` 는 이 이름을 그대로 Gemini 프롬프트의
# "현재 설명할 지표" 자리에 넣기 때문에, AI 는 **옛 이름**("공포지수 비대칭도",
# "합성선물 가격 차이")을 보고 설명을 쓰는데 화면은 그 코멘트를 **새 이름**
# ("VKOSPI 공포지수", "선물 베이시스") 옆에 붙여 보여줬습니다. 이름과 설명이 서로 다른
# 것을 가리키는 상태였고, 두 이름은 실제로 가리키는 지표 자체가 다릅니다
# (#70 에서 프록시 → KRX 실측으로 바뀌면서 내용이 바뀐 것 — 그때 화면 표기명만 고치고
#  AI 쪽 사전은 같이 못 고쳤습니다).
#
# 그래서 **계산에 쓰지 않는 순수 표시용 사전**을 이 파일(이미 매크로 상수의 단일 출처)로
# 올리고, `utils/macro_ai.py` 가 자기 사전을 갖는 대신 여기서 import 하게 했습니다.
# `utils/` 안에 두는 이유는 순환 import 를 피하기 위해서입니다 — 화면(`web/`, `views/`)이
# `utils/` 를 읽는 방향은 이미 존재하지만 그 반대는 없습니다.
#
# ⚠️ 두 화면 파일(`views/macro_view.py`, `web/pages/macro_page.py`)의 리터럴은
#    **일부러 그대로 뒀습니다.** 그 둘이 글자 단위로 같은지를 검사하는 테스트가 이미
#    있고(tests/test_web_session_isolation.py [8]), Streamlit 쪽 파일은 컷오버 유예 기간
#    동안 손대지 않기로 돼 있기 때문입니다. 대신 이 사전이 그 둘과 어긋나지 않는지는
#    tests/test_macro_scoring.py 가 매번 대조합니다 — 값이 갈라지면 테스트가 잡습니다.
#
# ⚠️ 키는 `RISK_WEIGHTS`(활성 지표) 와 정확히 일치해야 합니다. 내부 키 이름
#    (`VKOSPI_Skew`/`Synthetic_Futures`)은 일부러 옛 이름 그대로입니다 — 키를 바꾸면
#    market_history.csv 의 기존 컬럼과 연결이 끊겨 과거 기록을 읽을 수 없게 됩니다.
#    **화면에 보이는 이름만** 실제 내용대로 맞춥니다.
